// /api/admin (every route needs the admin login, except logging in)
import express from 'express';
import { requireAdmin } from '../../middleware/auth.js';
import { MAX_RESUME_MB } from '../files/files.service.js';
import * as adminAuth from './auth.controller.js';
import * as settings from './settings.controller.js';
import * as dashboard from './dashboard.controller.js';
import * as visitors from './visitors.controller.js';
import * as support from './support.controller.js';
import * as users from './users.controller.js';
import * as jobs from './jobs.controller.js';
import * as subscriptions from './subscriptions.controller.js';
import * as broadcasts from './broadcasts.controller.js';
import * as messages from './messages.controller.js';
import * as testing from './testing.controller.js';

const router = express.Router();
router.post('/admin/login', adminAuth.login);
router.post('/admin/logout', adminAuth.logout);
router.get('/admin/settings', requireAdmin, settings.get);
router.get('/admin/stats', requireAdmin, dashboard.stats);
router.put('/admin/settings', requireAdmin, settings.update);
router.get('/admin/visitors', requireAdmin, visitors.list);
router.post('/admin/ignored-ips', requireAdmin, visitors.ignore);
router.delete('/admin/ignored-ips', requireAdmin, visitors.unignore);
router.get('/admin/feedback', requireAdmin, support.list);
router.put('/admin/feedback/:id', requireAdmin, support.setDone);
router.put('/admin/users/:id/suspend', requireAdmin, users.suspend);
router.get('/admin/users', requireAdmin, users.list);
router.get('/admin/jobs', requireAdmin, jobs.list);
router.get('/admin/sample-jobs', requireAdmin, jobs.sampleStatus);
router.post('/admin/sample-jobs', requireAdmin, jobs.postSample);
router.delete('/admin/sample-jobs', requireAdmin, jobs.deleteSamples);
router.post('/admin/users/:id/login-as', requireAdmin, users.loginAs);
router.put('/admin/jobs/:id/closed', requireAdmin, jobs.setClosed);
router.get('/admin/subscriptions', requireAdmin, subscriptions.list);
router.get('/admin/users/:id', requireAdmin, users.get);
router.post('/admin/users/:id/confirm-email', requireAdmin, users.confirmEmail);
router.post('/admin/users/:id/resend-code', requireAdmin, users.resendCode);
router.put('/admin/users/:id/plan', requireAdmin, users.setPlan);
router.delete('/admin/users/:id', requireAdmin, users.remove);
router.get('/admin/broadcasts', requireAdmin, broadcasts.overview);
router.post('/admin/broadcasts', requireAdmin, broadcasts.send);
router.get('/admin/feedback/:id', requireAdmin, support.ticket);
router.post('/admin/feedback/:id/reply', requireAdmin, support.reply);
router.get('/admin/messages', requireAdmin, messages.inbox);
router.get('/admin/users/:id/messages', requireAdmin, messages.conversation);
router.post('/admin/users/:id/message', requireAdmin, messages.send);
router.post('/admin/testing/resume-text', requireAdmin, express.raw({ type: 'application/pdf', limit: `${MAX_RESUME_MB}mb` }), testing.resumeText);
router.post('/admin/testing/score', requireAdmin, testing.score);

export default router;
